#!/usr/bin/env python3
"""Validate Crowdin JSON catalogs and generate compile-time LVGL translation tables."""
from __future__ import annotations
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CATALOG_DIR = ROOT / "translations"
OUT_H = ROOT / "src/core/i18n_generated.h"
OUT_CPP = ROOT / "src/core/i18n_generated.cpp"
LANGUAGES = ("en", "tr", "vi")
PLACEHOLDER = re.compile(r"%(?:[-+#0 ]*\d*(?:\.\d+)?[hlLzjt]*[diuoxXfFeEgGaAcsp%])")


def main() -> int:
    catalogs = {}
    for code in LANGUAGES:
        path = CATALOG_DIR / f"{code}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict) or not data:
            raise ValueError(f"{path}: expected a non-empty JSON object")
        if any(not isinstance(k, str) or not isinstance(v, str) for k, v in data.items()):
            raise ValueError(f"{path}: keys and values must be strings")
        catalogs[code] = data

    keys = list(catalogs["en"])
    for code, data in catalogs.items():
        missing, extra = set(keys) - set(data), set(data) - set(keys)
        if missing or extra:
            raise ValueError(f"{code}: missing={sorted(missing)} extra={sorted(extra)}")
        for key in keys:
            source = sorted(PLACEHOLDER.findall(catalogs["en"][key]))
            target = sorted(PLACEHOLDER.findall(data[key]))
            if source != target:
                raise ValueError(f"{code}:{key}: placeholders {target} do not match {source}")

    enum_items = ",\n".join(f"  {key}" for key in keys)
    header = f"""// Generated by tools/i18n/generate_translations.py. DO NOT EDIT.
#pragma once
#include <stdint.h>
namespace core {{
enum class Str : uint16_t {{
{enum_items},
  Count
}};
namespace i18n_generated {{
extern const char* const kEnglish[];
extern const char* const kTurkish[];
extern const char* const kVietnamese[];
}}
}}
"""

    def cpp_literal(value: str) -> str:
        # JSON string escaping is compatible with C++ string literals for this catalog.
        return json.dumps(value, ensure_ascii=False)

    output = ['// Generated by tools/i18n/generate_translations.py. DO NOT EDIT.',
              '#include "i18n_generated.h"', 'namespace core::i18n_generated {']
    for code, symbol in (("en", "kEnglish"), ("tr", "kTurkish"), ("vi", "kVietnamese")):
        output.append(f"const char* const {symbol}[] = {{")
        output.extend(f"  {cpp_literal(catalogs[code][key])}," for key in keys)
        output.append("};")
        output.append(
            f'static_assert(sizeof({symbol}) / sizeof({symbol}[0]) == '
            f'static_cast<unsigned>(core::Str::Count), "{code} catalog size");'
        )
    output.append("}")

    OUT_H.write_text(header, encoding="utf-8")
    OUT_CPP.write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Validated {len(keys)} keys in {len(catalogs)} languages")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"i18n validation failed: {exc}", file=sys.stderr)
        raise SystemExit(1)
